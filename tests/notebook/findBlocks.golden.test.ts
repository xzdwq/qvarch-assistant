  it('recognizes every kind exactly as before the registry', () => {
    expect(findBlocks(CORPUS).map((b) => `${b.kind} ${b.line0}-${b.line1} ${JSON.stringify(b.src)}`)).toMatchSnapshot()
  })
  it('an empty note and a note of plain text have no blocks', () => {
    expect(findBlocks([''])).toEqual([])
    expect(findBlocks(['just', 'text'])).toEqual([])
  })
