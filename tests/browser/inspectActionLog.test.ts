import { describe, expect, it } from 'vitest'
import { ActionLog, coveredTime, groupSummary } from '../../src/shared/browser/inspect/actionLog'
import type { InspectReq } from '../../src/shared/browser/inspect/types'

const req = (id: string, start: number, type = 'XHR'): InspectReq => ({ id, method: 'GET', url: `https://a.test/${id}`, type, start })

describe('the inspector log of acts', () => {
  it('an act gathers its requests until the page is quiet; the next act opens a group of its own', () => {
    const log = new ActionLog()
    log.act({ kind: 'click', label: 'Сохранить', at: 1000 })
    log.reqStart(req('r1', 1010))
    log.reqStart(req('r2', 1020))
    log.tick(2000)
    // a request still going: the group waits for it
    expect(log.groups()[0].closed).toBe(false)
    log.reqUpdate('r1', { end: 1200, status: 200, size: 100 })
    log.reqUpdate('r2', { end: 1500, status: 500 })
    log.tick(1700)
    expect(log.groups()[0].closed).toBe(false)
    log.tick(2200)
    expect(log.groups()[0].closed).toBe(true)
    const s = groupSummary(log.groups()[0])
    expect(s).toMatchObject({ duration: 500, count: 2, sum: 190 + 480, wall: 490, failed: 1, bytes: 100 })
    log.act({ kind: 'click', label: 'Далее', at: 3000 })
    expect(log.groups().map((g) => g.label)).toEqual(['Сохранить', 'Далее'])
  })
  it('requests and errors with no act go to the page own group; a late answer still reaches its closed group', () => {
    const log = new ActionLog()
    log.reqStart(req('p', 100))
    log.note({ at: 120, level: 'error', text: 'boom' })
    expect(log.groups()).toHaveLength(1)
    expect(log.groups()[0].kind).toBe('background')
    log.act({ kind: 'click', label: 'X', at: 200 })
    log.reqUpdate('p', { end: 900 })
    expect(log.groups()[0].reqs[0].end).toBe(900)
    expect(log.groups()[0].notes).toHaveLength(1)
  })
  it('typing in one field is one group; a route right after a click is that click', () => {
    const log = new ActionLog()
    log.act({ kind: 'input', label: 'Поиск', target: '#q', at: 0 })
    log.act({ kind: 'input', label: 'Поиск', target: '#q', at: 500 })
    log.tick(1200)
    log.act({ kind: 'input', label: 'Поиск', target: '#q', at: 1300 })
    expect(log.groups()).toHaveLength(1)
    log.act({ kind: 'click', label: 'Отчёты', at: 5000 })
    log.act({ kind: 'route', label: '/reports', at: 5050, url: 'https://a.test/reports' })
    expect(log.groups()).toHaveLength(2)
    expect(log.groups()[1].url).toBe('https://a.test/reports')
  })
  it('busy time, the response and shifts go to the group of their moment; only changed groups are told', () => {
    const log = new ActionLog()
    log.act({ kind: 'click', label: 'A', at: 0 })
    log.busy({ at: 10, ms: 120, items: [{ kind: 'event', name: 'BUTTON.onclick', src: 'app.js', at: 10, ms: 100 }] })
    log.busy({ at: 200, ms: 60, items: [{ kind: 'promise', name: 'Response.json.then', src: 'app.js', at: 200, ms: 50 }] })
    log.response(5, { total: 180, delay: 20, processing: 140, presentation: 20 })
    log.shift(30, 0.05)
    const g = log.groups()[0]
    expect(g.busy).toEqual({ count: 2, total: 180, max: 120, scripts: [{ src: 'app.js', ms: 150 }] })
    expect(g.tasks.map((x) => x.items[0].kind)).toEqual(['event', 'promise'])
    expect(g.shifts).toEqual([{ at: 30, value: 0.05 }])
    expect(g.response?.total).toBe(180)
    expect(g.shift).toBeCloseTo(0.05)
    expect(log.takeChanged()).toHaveLength(1)
    expect(log.takeChanged()).toHaveLength(0)
  })
  it('a group never gathers past its limit; overlaps are counted once', () => {
    const log = new ActionLog()
    log.act({ kind: 'click', label: 'A', at: 0 })
    log.reqStart({ ...req('ws', 1), type: 'WebSocket' })
    log.tick(20_000)
    expect(log.groups()[0].closed).toBe(true)
    expect(coveredTime([[0, 10], [5, 15], [20, 30]])).toBe(25)
  })
})
