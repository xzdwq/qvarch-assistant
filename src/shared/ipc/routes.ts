import type { QaApi } from '../api'

/**
 * The one contract of the window ↔ main process bridge: every method of `window.qa` (QaApi) — its channel and how it
 * crosses: `invoke` — asks and waits for the answer, `send` — tells (no answer), `event` — main → window (a
 * subscription). The preload builds `window.qa` from it, the main process registers its handlers by it — the names
 * and the argument types are QaApi's, written once.
 */
export type RouteKind = 'invoke' | 'send' | 'event'
export interface Route<K extends RouteKind = RouteKind> {
  kind: K
  channel: string
}
const invoke = (channel: string): Route<'invoke'> => ({ kind: 'invoke', channel })
const send = (channel: string): Route<'send'> => ({ kind: 'send', channel })
const event = (channel: string): Route<'event'> => ({ kind: 'event', channel })

/** Methods done in the preload itself (no crossing). */
export type LocalMethod = 'pathForFile'
export type BridgedMethod = Exclude<keyof QaApi, LocalMethod>

/** How a method's type says it crosses: a subscription (a callback in, an unsubscribe out), a promise — asked, else told. */
export type KindOf<F> = F extends (cb: never) => () => void ? 'event' : F extends (...a: never[]) => unknown ? (ReturnType<F> extends Promise<unknown> ? 'invoke' : 'send') : never

