/** The methods of each kind. */
export type InvokeMethod = { [K in BridgedMethod]: KindOf<QaApi[K]> extends 'invoke' ? K : never }[BridgedMethod]
export type SendMethod = { [K in BridgedMethod]: KindOf<QaApi[K]> extends 'send' ? K : never }[BridgedMethod]
export type EventMethod = { [K in BridgedMethod]: KindOf<QaApi[K]> extends 'event' ? K : never }[BridgedMethod]
/** What an event carries (its callback's arguments). */
export type EventArgs<K extends EventMethod> = QaApi[K] extends (cb: (...a: infer A) => void) => () => void ? A : never
